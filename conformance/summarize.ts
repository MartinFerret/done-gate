// Reads the Weaver live-check report, writes report/summary.md, and fails on any violation.
// Improvements and information are listed, never hidden, and never fail the run.
// Usage: node summarize.ts <live_check.json> <weaver exit code>
// Report format: https://github.com/open-telemetry/weaver/blob/v0.28.0/crates/weaver_live_check/README.md
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

interface Advice {
  readonly id: string;
  readonly level: string;
  readonly message: string;
}
interface Report {
  readonly statistics: {
    readonly total_entities_by_type: Record<string, number>;
    readonly matchers?: {
      readonly id: string;
      readonly matched: number;
      readonly errors: number;
    }[];
  };
}

const [file, weaverExit = '0'] = process.argv.slice(2);
if (!file) throw new Error('Usage: node summarize.ts <live_check.json> <weaver exit code>');
const report: Report = JSON.parse(readFileSync(file, 'utf8'));

function isAdvice(value: unknown): value is Advice {
  return typeof value === 'object' && value !== null && 'id' in value && 'level' in value;
}

/** Every finding in the report, wherever it is nested (resource, span, attribute, event). */
function collect(node: unknown, found: Advice[] = []): Advice[] {
  if (Array.isArray(node)) {
    for (const item of node) collect(item, found);
  } else if (typeof node === 'object' && node !== null) {
    for (const [key, value] of Object.entries(node)) {
      if (key === 'all_advice' && Array.isArray(value)) found.push(...value.filter(isAdvice));
      else collect(value, found);
    }
  }
  return found;
}

const counts = new Map<string, { advice: Advice; count: number }>();
for (const advice of collect(report)) {
  const key = `${advice.level}|${advice.id}|${advice.message}`;
  const entry = counts.get(key) ?? { advice, count: 0 };
  entry.count += 1;
  counts.set(key, entry);
}

const LEVELS = ['violation', 'improvement', 'information'];
const total = (level: string): number =>
  [...counts.values()].filter((e) => e.advice.level === level).reduce((n, e) => n + e.count, 0);
const { statistics } = report;
const spans = statistics.total_entities_by_type['span'] ?? 0;
const matched = (statistics.matchers ?? []).reduce((n, m) => n + m.matched, 0);

const lines = [
  '# Weaver live-check report',
  '',
  'Generated by `conformance/run.sh`. Do not edit.',
  '',
  `- Spans received: ${spans}, recognised as gate decisions: ${matched}`,
  ...LEVELS.map((level) => `- ${level}: ${total(level)}`),
  '',
  '| Level | Finding | Message | Count |',
  '|---|---|---|---|',
  ...[...counts.values()]
    .toSorted(
      (a, b) =>
        LEVELS.indexOf(a.advice.level) - LEVELS.indexOf(b.advice.level) ||
        a.advice.id.localeCompare(b.advice.id) ||
        a.advice.message.localeCompare(b.advice.message),
    )
    .map((e) => `| ${e.advice.level} | \`${e.advice.id}\` | ${e.advice.message} | ${e.count} |`),
  '',
];
writeFileSync(join(dirname(file), 'summary.md'), lines.join('\n'));
console.log(lines.join('\n'));

const problems: string[] = [];
if (total('violation') > 0) problems.push(`${total('violation')} violation(s)`);
if (weaverExit !== '0') problems.push(`Weaver exited with code ${weaverExit}`);
// A run that checked nothing must not pass.
if (spans === 0 || matched !== spans) {
  problems.push(`${matched} of ${spans} spans were checked as gate decisions`);
}
if (problems.length > 0) {
  console.error(`FAILED: ${problems.join(', ')}`);
  process.exit(1);
}
console.log('OK: 0 violations');
